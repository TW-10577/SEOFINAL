import { translateDataTerms } from '@seo/shared';

// UI language (English / Japanese). Keys are the English strings; {name} placeholders are filled from vars.
// The language lives in App state, so a switch re-renders the whole tree; `t` reads the current value.
export type Lang = 'en' | 'ja';

const STORAGE_KEY = 'logos-seo-lang';
let current: Lang = 'en';

export function readLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'ja' ? 'ja' : 'en';
  } catch {
    return 'en';
  }
}

export function setLang(lang: Lang) {
  current = lang;
  document.documentElement.lang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* per-viewer convenience only */
  }
}

export const currentLang = (): Lang => current;

/** Client data (segment, column and dimension names) in English when English is selected; as exported in Japanese. */
export const dataLabel = (text: string | null | undefined): string => (text == null ? '' : current === 'en' ? translateDataTerms(text) : text);

export function t(text: string, vars?: Record<string, string | number>): string {
  const s = current === 'ja' ? (JA[text] ?? text) : text;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : s;
}

